-- V1: baseline schema and reconciliation.
-- Safe on an empty database and on a database that Hibernate created earlier.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS departments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    name        varchar(100) NOT NULL,
    code        varchar(20)  NOT NULL,
    CONSTRAINT uk_departments_name UNIQUE (name),
    CONSTRAINT uk_departments_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS employees (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     timestamp(6),
    updated_at     timestamp(6),
    first_name     varchar(50)    NOT NULL,
    last_name      varchar(50)    NOT NULL,
    email          varchar(255)   NOT NULL,
    phone_number   varchar(255)   NOT NULL,
    salary         numeric(38, 2) NOT NULL,
    hire_date      date           NOT NULL,
    profile_photo  varchar(255),
    department_id  bigint         NOT NULL REFERENCES departments (id),
    CONSTRAINT uk_employees_email UNIQUE (email),
    CONSTRAINT uk_employees_phone UNIQUE (phone_number)
);

CREATE TABLE IF NOT EXISTS users (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    employee_id  bigint REFERENCES employees (id),
    username     varchar(255) NOT NULL,
    password     varchar(255) NOT NULL,
    role         varchar(255) NOT NULL,
    enabled      boolean      NOT NULL DEFAULT true,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_employee UNIQUE (employee_id),
    CONSTRAINT ck_users_role CHECK (role IN ('ROLE_ADMIN', 'ROLE_HR_MANAGER', 'ROLE_EMPLOYEE'))
);

CREATE TABLE IF NOT EXISTS announcement (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    title         varchar(255),
    message       varchar(3000),
    publish_date  date,
    expiry_date   date
);

CREATE TABLE IF NOT EXISTS attendance (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     bigint  NOT NULL REFERENCES employees (id),
    attendance_date date    NOT NULL,
    check_in_time   timestamp(6),
    check_out_time  timestamp(6),
    working_hours   interval second,
    late            boolean NOT NULL,
    overtime        boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS leave_requests (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    employee_id   bigint       NOT NULL REFERENCES employees (id),
    leave_type    varchar(255) NOT NULL,
    start_date    date         NOT NULL,
    end_date      date         NOT NULL,
    reason        varchar(500),
    status        varchar(255) NOT NULL,
    applied_date  date,
    CONSTRAINT ck_leave_type CHECK (leave_type IN
        ('ANNUAL', 'SICK', 'MATERNITY', 'PATERNITY', 'STUDY', 'UNPAID')),
    CONSTRAINT ck_leave_status CHECK (status IN
        ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS notifications (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    title        varchar(255) NOT NULL,
    message      varchar(1000),
    is_read      boolean      NOT NULL,
    employee_id  bigint
);

CREATE TABLE IF NOT EXISTS payroll (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          timestamp(6),
    updated_at          timestamp(6),
    employee_id         bigint         NOT NULL REFERENCES employees (id),
    payroll_month       varchar(7)     NOT NULL,
    basic_salary        numeric(12, 2) NOT NULL,
    house_allowance     numeric(12, 2) NOT NULL,
    transport_allowance numeric(12, 2) NOT NULL,
    bonus               numeric(12, 2) NOT NULL,
    deductions          numeric(12, 2) NOT NULL,
    tax                 numeric(12, 2) NOT NULL,
    net_salary          numeric(12, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS performance_reviews (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    employee_id  bigint       NOT NULL REFERENCES employees (id),
    review_date  date         NOT NULL,
    reviewer     varchar(255) NOT NULL,
    rating       integer      NOT NULL,
    comments     varchar(2000),
    goals        varchar(1000)
);

CREATE TABLE IF NOT EXISTS system_logs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    username     varchar(255) NOT NULL,
    role         varchar(255) NOT NULL,
    action       varchar(255) NOT NULL,
    description  varchar(1000)
);

-- ---------------------------------------------------------------------------
-- Reconcile a database that Hibernate created earlier
-- ---------------------------------------------------------------------------

ALTER TABLE notifications ADD COLUMN IF NOT EXISTS employee_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_notifications_employee') THEN
        ALTER TABLE notifications
            ADD CONSTRAINT fk_notifications_employee
            FOREIGN KEY (employee_id) REFERENCES employees (id) ON DELETE CASCADE;
    END IF;
END $$;

ALTER TABLE performance_reviews
    DROP COLUMN IF EXISTS score,
    DROP COLUMN IF EXISTS manager_comments,
    DROP COLUMN IF EXISTS employee_comments;

-- Convert payroll_month to YYYY-MM text. For bytea, only convert when every
-- value is valid UTF-8 text in YYYY-MM format; otherwise stop without changing it.
DO $$
DECLARE
    month_type text;
    bad_id bigint;
    month_value text;
BEGIN
    SELECT data_type INTO month_type
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'payroll'
      AND column_name = 'payroll_month';

    IF month_type IS NULL OR month_type = 'character varying' THEN
        RETURN;
    ELSIF month_type IN ('date', 'timestamp without time zone', 'timestamp with time zone') THEN
        ALTER TABLE payroll
            ALTER COLUMN payroll_month TYPE varchar(7)
            USING to_char(payroll_month, 'YYYY-MM');
    ELSIF month_type IN ('text', 'character') THEN
        ALTER TABLE payroll
            ALTER COLUMN payroll_month TYPE varchar(7)
            USING left(payroll_month, 7);
    ELSIF month_type = 'bytea' THEN
        FOR bad_id IN SELECT id FROM payroll ORDER BY id LOOP
            BEGIN
                SELECT convert_from(payroll_month, 'UTF8')
                  INTO month_value
                FROM payroll
                WHERE id = bad_id;
            EXCEPTION WHEN OTHERS THEN
                RAISE EXCEPTION 'Cannot safely convert payroll_month for payroll id %: stored bytes are not valid UTF-8. No conversion was performed.', bad_id;
            END;

            IF month_value !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' THEN
                RAISE EXCEPTION 'Cannot safely convert payroll_month for payroll id %: decoded value is not YYYY-MM. No conversion was performed.', bad_id;
            END IF;
        END LOOP;

        ALTER TABLE payroll
            ALTER COLUMN payroll_month TYPE varchar(7)
            USING convert_from(payroll_month, 'UTF8');
    ELSIF (SELECT count(*) FROM payroll) = 0 THEN
        ALTER TABLE payroll
            ALTER COLUMN payroll_month TYPE varchar(7)
            USING payroll_month::text;
    ELSE
        RAISE EXCEPTION
            'payroll.payroll_month has unsupported type % and contains rows; inspect and convert it to varchar(7) (YYYY-MM) manually, then redeploy',
            month_type;
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_employees_department ON employees (department_id);
CREATE INDEX IF NOT EXISTS idx_attendance_employee_date ON attendance (employee_id, attendance_date);
CREATE INDEX IF NOT EXISTS idx_leave_employee ON leave_requests (employee_id);
CREATE INDEX IF NOT EXISTS idx_leave_status ON leave_requests (status);
CREATE INDEX IF NOT EXISTS idx_payroll_employee ON payroll (employee_id);
CREATE INDEX IF NOT EXISTS idx_performance_employee ON performance_reviews (employee_id);
CREATE INDEX IF NOT EXISTS idx_notifications_employee_created ON notifications (employee_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_system_logs_created ON system_logs (created_at DESC);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM attendance GROUP BY employee_id, attendance_date HAVING count(*) > 1) THEN
        RAISE NOTICE 'Duplicate attendance rows exist; uq_attendance_employee_date was not created';
    ELSE
        CREATE UNIQUE INDEX IF NOT EXISTS uq_attendance_employee_date
            ON attendance (employee_id, attendance_date);
    END IF;

    IF EXISTS (SELECT 1 FROM payroll GROUP BY employee_id, payroll_month HAVING count(*) > 1) THEN
        RAISE NOTICE 'Duplicate payroll rows exist; uq_payroll_employee_month was not created';
    ELSE
        CREATE UNIQUE INDEX IF NOT EXISTS uq_payroll_employee_month
            ON payroll (employee_id, payroll_month);
    END IF;
END $$;
