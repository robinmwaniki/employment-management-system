package com.ems;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.testcontainers.postgresql.PostgreSQLContainer;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.ObjectOutputStream;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.YearMonth;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Recreates the shape of a database that Hibernate built with ddl-auto=update
 * before Flyway was introduced, fills it with data, and checks that the
 * migrations convert it without losing anything.
 */
class LegacySchemaMigrationTests {

    private static PostgreSQLContainer postgres;

    @BeforeAll
    static void startDatabase() {

        postgres = new PostgreSQLContainer("postgres:18-alpine");
        postgres.start();
    }

    @AfterAll
    static void stopDatabase() {

        postgres.stop();
    }

    @Test
    void legacyHibernateSchemaIsConvertedWithoutLosingData() throws Exception {

        createLegacySchemaWithData();

        Flyway flyway = Flyway.configure()
                .dataSource(
                        postgres.getJdbcUrl(),
                        postgres.getUsername(),
                        postgres.getPassword())
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("0")
                .load();

        flyway.migrate();

        // Running the migrations again must change nothing and must not fail.
        flyway.migrate();

        // The serialised YearMonth became readable text.
        assertThat(query("SELECT payroll_month FROM payroll")).isEqualTo("2026-10");
        assertThat(query("SELECT data_type FROM information_schema.columns "
                + "WHERE table_name = 'payroll' AND column_name = 'payroll_month'"))
                .isEqualTo("character varying");

        // The columns of the unused entity are gone, the review itself is kept.
        assertThat(query("SELECT count(*) FROM information_schema.columns "
                + "WHERE table_name = 'performance_reviews' AND column_name = 'score'"))
                .isEqualTo("0");
        assertThat(query("SELECT count(*) FROM performance_reviews")).isEqualTo("1");

        // Notifications gained an owner column; the old row is kept as staff-only.
        assertThat(query("SELECT count(*) FROM notifications WHERE employee_id IS NULL"))
                .isEqualTo("1");

        // The second migration ran as well.
        assertThat(query("SELECT count(*) FROM information_schema.tables "
                + "WHERE table_name = 'employee_photos'"))
                .isEqualTo("1");

        // Attendance durations are stored as nanoseconds, as Hibernate expects.
        assertThat(query("SELECT data_type FROM information_schema.columns "
                + "WHERE table_name = 'attendance' AND column_name = 'working_hours'"))
                .isEqualTo("numeric");
    }

    private void createLegacySchemaWithData() throws Exception {

        try (Connection connection = connection();
             Statement statement = connection.createStatement()) {

            statement.execute("""
                    CREATE TABLE departments (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6), updated_at timestamp(6),
                        name varchar(100) NOT NULL UNIQUE,
                        code varchar(20) NOT NULL UNIQUE
                    )""");

            statement.execute("""
                    CREATE TABLE employees (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6), updated_at timestamp(6),
                        first_name varchar(50) NOT NULL,
                        last_name varchar(50) NOT NULL,
                        email varchar(255) NOT NULL UNIQUE,
                        phone_number varchar(255) NOT NULL UNIQUE,
                        salary numeric(38,2) NOT NULL,
                        hire_date date NOT NULL,
                        profile_photo varchar(255),
                        department_id bigint NOT NULL REFERENCES departments (id)
                    )""");

            // payroll_month as Hibernate stored it: a Java-serialised YearMonth.
            statement.execute("""
                    CREATE TABLE payroll (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6), updated_at timestamp(6),
                        employee_id bigint NOT NULL REFERENCES employees (id),
                        payroll_month bytea NOT NULL,
                        basic_salary numeric(12,2) NOT NULL,
                        house_allowance numeric(12,2) NOT NULL,
                        transport_allowance numeric(12,2) NOT NULL,
                        bonus numeric(12,2) NOT NULL,
                        deductions numeric(12,2) NOT NULL,
                        tax numeric(12,2) NOT NULL,
                        net_salary numeric(12,2) NOT NULL
                    )""");

            // Two entities used to share this table, which left extra columns behind.
            statement.execute("""
                    CREATE TABLE performance_reviews (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6), updated_at timestamp(6),
                        employee_id bigint NOT NULL REFERENCES employees (id),
                        review_date date NOT NULL,
                        reviewer varchar(255) NOT NULL,
                        rating integer NOT NULL,
                        comments varchar(2000),
                        goals varchar(1000),
                        score integer NOT NULL,
                        manager_comments varchar(1000),
                        employee_comments varchar(1000)
                    )""");

            statement.execute("""
                    CREATE TABLE notifications (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        created_at timestamp(6), updated_at timestamp(6),
                        title varchar(255) NOT NULL,
                        message varchar(1000),
                        is_read boolean NOT NULL
                    )""");

            statement.execute("INSERT INTO departments (name, code) VALUES ('Engineering', 'ENG')");

            statement.execute("INSERT INTO employees (first_name, last_name, email, phone_number, "
                    + "salary, hire_date, department_id) VALUES "
                    + "('Jane', 'Doe', 'jane@example.com', '0700000000', 50000, DATE '2024-01-15', 1)");

            statement.execute("INSERT INTO notifications (title, message, is_read) "
                    + "VALUES ('Old', 'Shared notification', false)");

            statement.execute("INSERT INTO performance_reviews "
                    + "(employee_id, review_date, reviewer, rating, comments, goals, score) "
                    + "VALUES (1, DATE '2026-01-10', 'Manager', 4, 'Good', 'Grow', 80)");
        }

        try (Connection connection = connection();
             PreparedStatement insert = connection.prepareStatement(
                     "INSERT INTO payroll (employee_id, payroll_month, basic_salary, house_allowance, "
                             + "transport_allowance, bonus, deductions, tax, net_salary) "
                             + "VALUES (1, ?, 1, 1, 1, 1, 1, 1, 1)")) {

            insert.setBytes(1, serialize(YearMonth.of(2026, 10)));
            insert.executeUpdate();
        }
    }

    /** Serialises the object exactly the way Hibernate did for the old column. */
    private byte[] serialize(Object value) throws IOException {

        ByteArrayOutputStream bytes = new ByteArrayOutputStream();

        try (ObjectOutputStream out = new ObjectOutputStream(bytes)) {
            out.writeObject(value);
        }

        return bytes.toByteArray();
    }

    private String query(String sql) throws SQLException {

        try (Connection connection = connection();
             Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery(sql)) {

            result.next();

            return result.getString(1);
        }
    }

    private Connection connection() throws SQLException {

        return DriverManager.getConnection(
                postgres.getJdbcUrl(),
                postgres.getUsername(),
                postgres.getPassword());
    }
}
